"""Package only verified challenges; artifacts contain data, never model-authored executable code."""
import json
import shutil
import zipfile
from pathlib import Path

from backend.schemas import Manifest


def package_challenge(root: Path, artifact_root: Path, manifest: Manifest, result: dict,
                      project_dir: Path | None) -> dict:
    if not result["verified"]:
        raise ValueError("Only verified outcomes may become a challenge package")
    base = result["artifacts"]["summary"].rsplit("/", 1)[0]
    extra = {}
    for variant in ("buggy", "fixed"):
        record = next(row for row in reversed(result["runs"]) if row["variant"] == variant and row["phase"] == "validation")
        directory = (root / "evidence" / record["artifactDirectory"]).resolve()
        if not directory.is_relative_to((root / "evidence/jobs").resolve()):
            raise ValueError("Player evidence directory is outside the job root")
        for original, packaged in (("player.html", f"player-{variant}.html"), ("trace.zip", f"{variant}-trace.zip"),
                                    ("recording.webm", f"{variant}-recording.webm")):
            source = directory / original
            if not source.is_file() or source.stat().st_size > 8 * 1024 * 1024:
                raise ValueError("Verified replay is missing a bounded player, trace or recording artifact")
            shutil.copyfile(source, artifact_root / packaged)
            extra[{"player.html": f"{variant}Player", "trace.zip": f"{variant}Trace", "recording.webm": f"{variant}Recording"}[original]] = base + "/" + packaged
    result["player"] = {"kind": "offline-browser-cartridge", "buggyUrl": extra["buggyPlayer"], "fixedUrl": extra["fixedPlayer"],
                        "securityNote": "Render only in a scripts-only sandbox iframe. Player feedback is not verifier evidence; recorded browser assertions remain authoritative."}
    replay = {"schemaVersion": 1, "challengeId": manifest.id, "actions": result["actions"],
              "assertion": result["assertion"], "completion": result["completion"],
              "invariantHash": result["invariantHash"], "seed": result["seed"], "schedule": result["schedule"]}
    challenge = {"schemaVersion": 1, "title": manifest.title, "goal": manifest.goal, "hint": manifest.hint,
                 "explanation": manifest.explanation, "allowedTargets": manifest.allowedTargets, **replay,
                 "sourceHashes": result["sourceHashes"], "provenance": result["provenance"],
                 "evidence": {"summary": "summary.json", "runs": "runs.json", "regression": "regression.test.mjs"},
                 "player": {**result["player"], "buildRunner": result["runner"],
                            "note": ("Uploaded source was bundled only in Modal. " if project_dir else "The trusted seed was bundled by the local worker. ") + "This standalone cartridge uses a bounded in-memory network schedule and has no live provider calls."}}
    (artifact_root / "challenge.json").write_text(json.dumps(challenge, indent=2))
    (artifact_root / "replay.json").write_text(json.dumps(replay, indent=2))
    source_root = project_dir or root / "fixtures" / manifest.id
    with zipfile.ZipFile(artifact_root / "source.zip", "w", zipfile.ZIP_DEFLATED) as archive:
        for variant in ("buggy", "fixed"):
            archive.writestr(f"{variant}/App.tsx", (source_root / variant / "App.tsx").read_text())
        archive.writestr("manifest.json", manifest.model_dump_json(indent=2))
    return {"challenge": base + "/challenge.json", "replay": base + "/replay.json", "source": base + "/source.zip", **extra}


def render_regression(manifest: Manifest, hashes: dict, frozen: str, actions: list[dict], project_dir: Path | None) -> str:
    """One canonical template; source/model text cannot supply executable test code."""
    return f'''// Generated by the deterministic BugArcade packager. No provider credentials required.
// Original source hashes: {json.dumps(hashes, sort_keys=True)}
import {{ test }} from 'node:test';
import assert from 'node:assert/strict';
import {{ execFileSync }} from 'node:child_process';
import {{ readFileSync }} from 'node:fs';
import path from 'node:path';
test({json.dumps(manifest.title + " invariant")}, () => {{
  const variant = process.env.VARIANT || 'fixed';
  assert.ok(['buggy','fixed'].includes(variant), 'VARIANT must be buggy or fixed');
  {"assert.equal(process.env.BUGARCADE_SANDBOX, '1', 'Submitted regression must run inside the authorized sandbox'); const projectDir = process.env.BUGARCADE_PROJECT_DIR; assert.ok(projectDir && path.isAbsolute(projectDir), 'BUGARCADE_PROJECT_DIR must name the submitted starter directory; no seed fallback is allowed'); assert.equal(JSON.parse(readFileSync(path.join(projectDir, 'manifest.json'), 'utf8')).id, " + json.dumps(manifest.id) + ");" if project_dir else "// This regression exercises the shipped seed fixture; imports above also support submitted starters."}
  const result = JSON.parse(execFileSync('node', ['worker/cli.mjs'], {{
    input: JSON.stringify({{challengeId:{json.dumps(manifest.id)}, variant, assertionHash:{json.dumps(frozen)}, actions:{json.dumps(actions)}{', projectDir' if project_dir else ''}}}) + '\\n', encoding:'utf8', timeout:45000
  }}));
  assert.equal(result.assertion?.hash, {json.dumps(frozen)}, 'Immutable invariant changed');
  assert.equal(result.status, 'passed', JSON.stringify(result.assertion));
}});
'''
